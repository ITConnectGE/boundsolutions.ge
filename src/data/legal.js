// The pages are now edited as rich text (WYSIWYG) via the CMS. Convert the
// structured default above into an HTML body per locale so the built-in content
// is the starting point; admin overrides (col.privacy / col.terms) replace it.
const TRANSLATION_NOTE =
  '<p><em>This is an unofficial translation. In the event of any discrepancy, the Georgian version prevails.</em></p>'

function policyToHtml(policy, { translated = false } = {}) {
  const build = (locale) =>
    (translated && locale === 'en' ? TRANSLATION_NOTE : '') +
    policy.sections
      .map((s) => {
        let html = `<h2>${s.title[locale]}</h2>`
        for (const p of s.paras?.[locale] || []) html += `<p>${p}</p>`
        if (s.bullets) {
          // `list: 'geo'` keeps the ა) ბ) გ) lettering of the signed document,
          // `list: 'num'` its 1. 2. 3.; without it the clause is a plain bullet.
          const items = (s.bullets[locale] || []).map((b) => `<li>${b}</li>`).join('')
          html += s.list ? `<ol class="${s.list}">${items}</ol>` : `<ul>${items}</ul>`
        }
        return html
      })
      .join('')
  return { updated: policy.updated, body: { ka: build('ka'), en: build('en') } }
}

export const privacyDefault = policyToHtml(privacy, { translated: true })
export const termsDefault = policyToHtml(terms)
export const cookiesDefault = policyToHtml(cookies, { translated: true })
